const STORAGE_KEY = 'vernunt_kid_stories_v1';

export function getStoredKidStories(): KidStory[] {
  if (typeof window === 'undefined') return INITIAL_KID_STORIES;
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(INITIAL_KID_STORIES));
      return INITIAL_KID_STORIES;
    }
    const parsed: KidStory[] = JSON.parse(raw);
    if (!Array.isArray(parsed) || parsed.length === 0) {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(INITIAL_KID_STORIES));
      return INITIAL_KID_STORIES;
    }
    return parsed;
  } catch (err) {
    console.error('Failed to load kid stories from localStorage:', err);
    return INITIAL_KID_STORIES;
  }
}

export function saveKidStories(stories: KidStory[]): void {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(stories));
  } catch (err) {
    console.error('Failed to save kid stories to localStorage:', err);
  }
}

export function getApprovedKidStories(): KidStory[] {
  return getStoredKidStories().filter(s => s.status === 'approved');
}

export function getKidStoryBySlug(slug: string): KidStory | undefined {
  const stories = getStoredKidStories();
  return stories.find(s => s.slug === slug || s.id === slug);
}

export function submitParentKidStory(data: Omit<KidStory, 'id' | 'submittedAt' | 'status' | 'slug' | 'viewsCount' | 'likesCount'>): KidStory {
  const stories = getStoredKidStories();
  const slugBase = `${data.kidName.toLowerCase().replace(/[^a-z0-9]+/g, '-')}-${data.title.toLowerCase().replace(/[^a-z0-9]+/g, '-').slice(0, 40)}`;
  const cleanSlug = slugBase.replace(/(^-|-$)/g, '');
  const id = `story-${Date.now()}`;
  
  const newStory: KidStory = {
    ...data,
    id,
    slug: cleanSlug,
    submittedAt: new Date().toISOString(),
    status: 'pending_approval',
    viewsCount: 1,
    likesCount: 0
  };
  
  const updated = [newStory, ...stories];
  saveKidStories(updated);
  return newStory;
}

export function approveKidStory(storyId: string): KidStory | undefined {
  const stories = getStoredKidStories();
  const index = stories.findIndex(s => s.id === storyId);
  if (index === -1) return undefined;
  
  stories[index].status = 'approved';
  stories[index].approvedAt = new Date().toISOString();
  saveKidStories(stories);
  return stories[index];
}

export function rejectKidStory(storyId: string, reason?: string): KidStory | undefined {
  const stories = getStoredKidStories();
  const index = stories.findIndex(s => s.id === storyId);
  if (index === -1) return undefined;
  
  stories[index].status = 'rejected';
  stories[index].rejectionReason = reason || 'Does not meet editorial guidelines';
  saveKidStories(stories);
  return stories[index];
}

export function incrementStoryViews(storyId: string): void {
  const stories = getStoredKidStories();
  const target = stories.find(s => s.id === storyId || s.slug === storyId);
  if (target) {
    target.viewsCount = (target.viewsCount || 0) + 1;
    saveKidStories(stories);
  }
}

export function updateKidStoryByAdmin(storyId: string, updates: Partial<KidStory>): KidStory | undefined {
  const stories = getStoredKidStories();
  const index = stories.findIndex(s => s.id === storyId);
  if (index === -1) return undefined;
  
  const current = stories[index];
  const updated: KidStory = {
    ...current,
    ...updates,
    id: current.id, // preserve immutable ID
    slug: updates.title && updates.title !== current.title
      ? `${(updates.kidName || current.kidName).toLowerCase().replace(/[^a-z0-9]+/g, '-')}-${updates.title.toLowerCase().replace(/[^a-z0-9]+/g, '-').slice(0, 40)}`.replace(/(^-|-$)/g, '')
      : current.slug
  };
  
  stories[index] = updated;
  saveKidStories(stories);
  return updated;
}

export function deleteKidStory(storyId: string): boolean {
  const stories = getStoredKidStories();
  const filtered = stories.filter(s => s.id !== storyId);
  if (filtered.length === stories.length) return false;
  saveKidStories(filtered);
  return true;
}

