export function getKidBooks(storiesList?: KidStory[]): KidBookProfile[] {
  const source = storiesList && storiesList.length > 0 ? storiesList : getApprovedKidStories();
  const grouped = new Map<string, KidStory[]>();

  for (const story of source) {
    const key = story.kidName.trim().toLowerCase();
    if (!grouped.has(key)) {
      grouped.set(key, []);
    }
    grouped.get(key)!.push(story);
  }

  const books: KidBookProfile[] = [];

  for (const [_, kidStories] of grouped.entries()) {
    // Sort stories by chapter number ascending or submittedAt
    kidStories.sort((a, b) => {
      const chA = a.chapterNumber || 1;
      const chB = b.chapterNumber || 1;
      if (chA !== chB) return chA - chB;
      return new Date(a.submittedAt).getTime() - new Date(b.submittedAt).getTime();
    });

    const first = kidStories[0];
    const latest = kidStories[kidStories.length - 1];
    const totalViews = kidStories.reduce((sum, s) => sum + (s.viewsCount || 0), 0);
    const totalLikes = kidStories.reduce((sum, s) => sum + (s.likesCount || 0), 0);

    const theme = getBookThemeForCategory(latest.category, latest.kidName);

    books.push({
      kidName: latest.kidName,
      kidAge: latest.kidAge,
      kidCity: latest.kidCity,
      category: latest.category,
      photoUrl: latest.photoUrl,
      stories: kidStories,
      chapterCount: kidStories.length,
      latestStory: latest,
      earliestStory: first,
      coverColor: theme.name,
      totalViews,
      totalLikes,
      parentName: latest.parentName,
      parentEmail: latest.parentEmail,
      parentPhone: latest.parentPhone,
      instagramUrl: latest.instagramUrl,
      instagramFollowers: latest.instagramFollowers
    });
  }

  // Sort books by latest activity or total stories
  return books.sort((a, b) => b.chapterCount - a.chapterCount || b.totalViews - a.totalViews);
}

